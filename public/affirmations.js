function hash(value) {
  let result = 2166136261;
  for (const character of value) {
    result ^= character.charCodeAt(0);
    result = Math.imul(result, 16777619);
  }
  return result >>> 0;
}

function getArchetypePool(archetypeName) {
  if (!archetypeName) return pools.general;
  const key = Object.keys(pools).find(name => name !== "general" && archetypeName.includes(name));
  return [...(key ? pools[key] : []), ...pools.general];
}

export function getDailyAffirmation(uid, archetypeName = "", date = new Date()) {
  const pool = getArchetypePool(archetypeName);
  const dailyPoolSize = pool.length * encouragements.length;
  const day = Math.floor(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()) / 86400000);
  const offset = hash(uid) % dailyPoolSize;
  const index = ((day % dailyPoolSize) + offset) % dailyPoolSize;
  const affirmation = pool[index % pool.length];
  const encouragement = encouragements[Math.floor(index / pool.length)];
  return `${affirmation} ${encouragement}`;
}
